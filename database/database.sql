-- =====================================================================
--  Haven Goods - Online Store Database
--  Engine: SQLite 3 (loaded automatically by the app on first start)
--  Tables: categories, products, product_images, users, reviews,
--          wishlist, orders, order_items, order_status_history
-- =====================================================================

PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS order_status_history;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS wishlist;
DROP TABLE IF EXISTS reviews;
DROP TABLE IF EXISTS product_images;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;

-- Product categories
CREATE TABLE categories (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Products. old_price is the price before discount (NULL = no discount).
CREATE TABLE products (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    category_id INTEGER NOT NULL,
    name        VARCHAR(150) NOT NULL,
    brand       VARCHAR(100),
    description TEXT NOT NULL,
    price       DECIMAL(10,2) NOT NULL CHECK (price >= 0),
    old_price   DECIMAL(10,2),
    stock       INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    image       VARCHAR(255) NOT NULL,              -- main image
    featured    INTEGER NOT NULL DEFAULT 0,         -- 1 = shown on home page
    sold_count  INTEGER NOT NULL DEFAULT 0,
    warranty    VARCHAR(100),
    specs       TEXT,                               -- one "Key: Value" per line
    created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE RESTRICT
);

-- Extra photos for the product gallery
CREATE TABLE product_images (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    product_id INTEGER NOT NULL,
    image      VARCHAR(255) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- Customers and admins. password_hash format: <salt hex>:<scrypt hash hex>
CREATE TABLE users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    phone         VARCHAR(30),
    address       VARCHAR(255),
    city          VARCHAR(100),
    role          VARCHAR(20) NOT NULL DEFAULT 'customer' CHECK (role IN ('customer','admin')),
    created_at    DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Product ratings and reviews (user_id is NULL for imported reviews)
CREATE TABLE reviews (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    product_id    INTEGER NOT NULL,
    user_id       INTEGER,
    reviewer_name VARCHAR(100) NOT NULL,
    rating        INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment       TEXT,
    created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE SET NULL
);

-- Customer wishlists
CREATE TABLE wishlist (
    user_id    INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, product_id),
    FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- Orders. Customer details are copied in so the order keeps a record of
-- where it was shipped even if the profile changes later.
CREATE TABLE orders (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id        INTEGER NOT NULL,
    customer_name  VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    phone          VARCHAR(30)  NOT NULL,
    address        VARCHAR(255) NOT NULL,
    city           VARCHAR(100) NOT NULL,
    payment_method VARCHAR(20)  NOT NULL CHECK (payment_method IN ('COD','CARD','WALLET')),
    payment_status VARCHAR(30)  NOT NULL DEFAULT 'Unpaid',
    status         VARCHAR(20)  NOT NULL DEFAULT 'Pending'
                   CHECK (status IN ('Pending','Processing','Shipped','Delivered','Cancelled')),
    subtotal       DECIMAL(10,2) NOT NULL,
    shipping       DECIMAL(10,2) NOT NULL DEFAULT 0,
    total          DECIMAL(10,2) NOT NULL,
    notes          TEXT,
    checkout_token VARCHAR(64) UNIQUE,     -- one-time token: stops the same checkout creating two orders
    created_at     DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE order_items (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id     INTEGER NOT NULL,
    product_id   INTEGER,
    product_name VARCHAR(150) NOT NULL,
    image        VARCHAR(255),
    price        DECIMAL(10,2) NOT NULL,
    quantity     INTEGER NOT NULL CHECK (quantity > 0),
    FOREIGN KEY (order_id)   REFERENCES orders(id)   ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
);

-- Tracking timeline: one row each time an order's status changes
CREATE TABLE order_status_history (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id   INTEGER NOT NULL,
    status     VARCHAR(20) NOT NULL,
    note       VARCHAR(255),
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);

CREATE INDEX idx_products_category   ON products(category_id);
CREATE INDEX idx_product_images      ON product_images(product_id);
CREATE INDEX idx_reviews_product     ON reviews(product_id);
CREATE INDEX idx_orders_user         ON orders(user_id);
CREATE INDEX idx_order_items_order   ON order_items(order_id);
CREATE INDEX idx_status_history      ON order_status_history(order_id);
CREATE INDEX idx_orders_status       ON orders(status);
CREATE INDEX idx_wishlist_product    ON wishlist(product_id);
CREATE INDEX idx_reviews_user        ON reviews(user_id);
CREATE INDEX idx_products_featured   ON products(featured, sold_count);

